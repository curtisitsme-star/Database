--TAO BANG KHACH HANG

CREATE TABLE KHACHHANG
(
	MAKH char(4) NOT NULL,
	HOTEN varchar(40),
	DCHI varchar(50),
	SODT varchar(20),
	NGSINH smalldatetime,
	NGDK smalldatetime,
	DOANHSO money
)

--TAO BANG NHANVIEN
CREATE TABLE NHANVIEN
(
	MANV char(4) NOT NULL,
	HOTEN varchar(40),
	SODT varchar(20),
	NGVL smalldatetime
)

--TAO BANG SANPHAM
CREATE TABLE SANPHAM
(
	MASP char(4) NOT NULL,
	TENSP varchar(40),
	DVT varchar(20),
	NUOCSX varchar(40),
	GIA money
)

--TAO BANG HOADON
CREATE TABLE HOADON
(
	SOHD int NOT NULL,
	NGHD smalldatetime,
	MAKH char(4),
	MANV char(4),
	GIATRI money
)

--TAO BANG CTHD

CREATE TABLE CTHD
(
	SOHD int NOT NULL,
	MASP char(4) NOT NULL,
	SL int
)

--TAO KHOA CHINH

ALTER TABLE KHACHHANG 
ADD CONSTRAINT PK_KH PRIMARY KEY (MAKH)

ALTER TABLE NHANVIEN 
ADD CONSTRAINT PK_NV PRIMARY KEY (MANV)

ALTER TABLE SANPHAM 
ADD CONSTRAINT PK_PS PRIMARY KEY (MASP)

ALTER TABLE HOADON 
ADD CONSTRAINT PK_HD PRIMARY KEY (SOHD)

ALTER TABLE CTHD 
ADD CONSTRAINT PK_CTHD PRIMARY KEY (SOHD,MASP)

--TAO KHOA NGOAI

ALTER TABLE HOADON 
ADD CONSTRAINT FK_HD_KH FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH),
	CONSTRAINT FK_HD_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)

ALTER TABLE CTHD 
ADD CONSTRAINT FK_CTHD_SHD FOREIGN KEY (SOHD) REFERENCES HOADON(SOHD),
	CONSTRAINT FK_CTHD_MSP FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)

--XOA BANG 

